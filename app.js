const escapeHtml = (value = "") => value.replace(/[&<>'"]/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;",'"':"&quot;"}[c]));

function highlightValue(value) {
  const tokenPattern = /(\b[a-z][a-z0-9._-]*(?==))|([A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,})|(\b(?:\d{1,3}\.){3}\d{1,3}\b)|(\b(?:pass(?:ed)?|fail(?:ed)?|softfail|temperror|permerror)\b)|(\b(?:ESMTPS?|SMTP|MAPI|PIPE|TLS(?:v|_)?[\d_.]+)\b)|(\b(?:Mon|Tue|Wed|Thu|Fri|Sat|Sun),?\s+\d{1,2}\s+[A-Z][a-z]{2}\s+\d{4}\s+\d{2}:\d{2}(?::\d{2})?\s+(?:[+-]\d{4}|UTC|GMT)\b)/gi;
  let html = "";
  let cursor = 0;
  for (const match of value.matchAll(tokenPattern)) {
    html += escapeHtml(value.slice(cursor, match.index));
    let className = "syntax-date";
    if (match[1]) className = "syntax-parameter";
    else if (match[2]) className = "syntax-email";
    else if (match[3]) className = "syntax-ip";
    else if (match[4]) className = /^pass/i.test(match[0]) ? "syntax-pass" : "syntax-fail";
    else if (match[5]) className = "syntax-protocol";
    html += `<span class="${className}">${escapeHtml(match[0])}</span>`;
    cursor = match.index + match[0].length;
  }
  return html + escapeHtml(value.slice(cursor));
}

function highlightHeader(raw) {
  return raw.split("\n").map(line => {
    const field = line.match(/^([^\s:][^:]*)(:)(.*)$/);
    if (!field) return highlightValue(line);
    return `<span class="syntax-field">${escapeHtml(field[1])}</span><span class="syntax-colon">:</span>${highlightValue(field[3])}`;
  }).join("\n");
}

