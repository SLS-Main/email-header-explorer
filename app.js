function renderVerdict() {
  const failed = Object.entries(state.auth).filter(([, value]) => value === "fail").map(([key]) => key.toUpperCase());
  const passed = Object.values(state.auth).filter(value => value === "pass").length;
  const card = $("#verdictCard");
  card.className = "verdict-card " + (failed.length ? "danger" : passed >= 2 ? "safe" : "caution");
  $("#verdictIcon").textContent = failed.length ? "!" : passed >= 2 ? "✓" : "?";
  $("#verdictTitle").textContent = failed.length ? "Authentication concerns found" : passed >= 2 ? "Key checks passed" : "Limited trust evidence";
  $("#verdictText").textContent = failed.length ? `${failed.join(", ")} failed in the latest recorded results. Review the route and forwarding context.` : passed >= 2 ? "The latest recorded sender checks support the message's identity." : "There is not enough current authentication data for a strong conclusion.";
}

