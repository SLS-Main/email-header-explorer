function parseHeaders(raw) {
  const fields = [];
  const lines = raw.replace(/\r\n/g, "\n").split("\n");
  let current = null;
  lines.forEach((line, index) => {
    if (/^[ \t]/.test(line) && current) {
      current.value += " " + line.trim();
      current.raw += "\n" + line;
      return;
    }
    const match = line.match(/^([^\s:][^:]*):\s*(.*)$/);
    if (match) {
      current = { name: match[1].trim(), key: match[1].trim().toLowerCase(), value: match[2].trim(), raw: line, line: index + 1 };
      fields.push(current);
    } else if (line.trim()) {
      current = null;
    }
  });
  return fields.map(field => ({ ...field, ...describeField(field) }));
}

function describeField(field) {
  let info = FIELD_INFO[field.key];
  if (!info && field.key.startsWith("received")) info = FIELD_INFO.received;
  if (!info && field.key.startsWith("x-note")) info = FIELD_INFO["x-note"];
  if (!info && /^(x-ms|x-microsoft|x-forefront|x-eop|x-cloud|x-policy|x-primary|x-gbudb|x-signature|x-mlmodel)/.test(field.key)) {
    info = ["Provider-specific diagnostic", "Operational metadata added by a mail or security provider. It can help administrators investigate filtering and transport behavior.", "Vendor diagnostics"];
  }
  if (!info && /^(thread-|accept-language|x-mailbox-line)/.test(field.key)) info = ["Message client metadata", "Metadata added by the sender's mail application to support display, language, or conversation features.", "Message"];
  if (!info) info = [humanize(field.name), "An additional email metadata field. Its exact meaning depends on the system that added it.", "Other"];
  return { friendly: info[0], description: info[1], category: info[2] };
}

function humanize(name) {
  return name.replace(/^x-/i, "").split("-").map(word => word ? word[0].toUpperCase() + word.slice(1).toLowerCase() : "").join(" ");
}

function parseHop(field, index, total) {
  const value = field.value;
  const fromMatch = value.match(/\bfrom\s+([^\s(;,]+)/i);
  const byMatch = value.match(/\bby\s+([^\s(;,]+)/i);
  const ips = [...value.matchAll(/(?:\[)?((?:\d{1,3}\.){3}\d{1,3}|[a-f0-9]{0,4}:[a-f0-9:]+)(?:\])?/gi)].map(m => m[1]);
  const timePart = value.includes(";") ? value.slice(value.lastIndexOf(";") + 1).trim() : "";
  const parsedTime = Date.parse(timePart);
  const tls = value.match(/TLS(?:v|_)?[\d_.]+|ESMTPS?|SMTP|MAPI|PIPE/i);
  const cipher = value.match(/cipher=([A-Z0-9_]+)/i);
  const from = fromMatch?.[1] || (index === 0 ? "Origin system" : "Unidentified server");
  const by = byMatch?.[1] || (index === total - 1 ? "Destination system" : "Unidentified server");
  return { from, by, ips, time: Number.isNaN(parsedTime) ? null : new Date(parsedTime), timeRaw: timePart || "Not recorded", protocol: tls?.[0] || "Not stated", cipher: cipher?.[1] || null, secure: /TLS|ESMTPS/i.test(value), raw: field.value };
}

function identifyProvider(host) {
  const value = host.toLowerCase();
  if (/outlook|office365|microsoft|protection\.outlook|namprd/.test(value)) return "Microsoft 365";
  if (/appriver/.test(value)) return "AppRiver security gateway";
  if (/checkpoint|cloud-sec-av/.test(value)) return "Check Point cloud security";
  if (/google|gmail/.test(value)) return "Google Workspace";
  if (/amazonses|amazonaws/.test(value)) return "Amazon Web Services";
  if (/mimecast/.test(value)) return "Mimecast security gateway";
  if (/proofpoint/.test(value)) return "Proofpoint security gateway";
  if (/localhost|unidentified|origin|destination/.test(value)) return "Unidentified mail system";
  return "Independent mail system";
}

function classifyAddress(ip) {
  if (!ip) return "No IP address recorded";
  if (/^(10\.|127\.|192\.168\.|169\.254\.)/.test(ip) || /^172\.(1[6-9]|2\d|3[01])\./.test(ip) || /^(::1|f[cd]|fe80)/i.test(ip)) return "Private or internal address";
  if (ip.includes(":")) return "Public IPv6 address";
  return "Public IPv4 address";
}

function formatHopDelay(index) {
  if (index === 0) return "First recorded event";
  const previous = state.hops[index - 1].time;
  const current = state.hops[index].time;
  if (!previous || !current) return "Cannot calculate";
  const seconds = Math.round((current - previous) / 1000);
  if (seconds < 0) return `${Math.abs(seconds)} sec clock difference`;
  if (seconds < 60) return `${seconds} sec after prior hop`;
  return `${Math.floor(seconds / 60)}m ${seconds % 60}s after prior hop`;
}

function getAuth(fields) {
  const sources = fields.filter(f => /^(authentication-results|arc-authentication-results|x-ms-exchange-authentication-results)$/.test(f.key));
  const current = sources[0]?.value || "";
  const result = {};
  ["spf", "dkim", "dmarc", "arc"].forEach(type => {
    const match = current.match(new RegExp(`(?:^|[;\\s])${type}=(pass|fail|softfail|neutral|none|temperror|permerror)`, "i"));
    result[type] = match ? match[1].toLowerCase() : "none";
  });
  return result;
}

function resultCopy(type, status) {
  const text = {
    spf: ["Sending server", "Checks whether the connecting IP was approved by the envelope sender's domain."],
    dkim: ["Message signature", "Checks whether a domain signature is valid and signed content stayed intact."],
    dmarc: ["Domain alignment", "Checks that SPF or DKIM passes and aligns with the address shown in From."],
    arc: ["Forwarding history", "Checks whether authentication evidence preserved by forwarding systems is trustworthy."]
  }[type];
  const verdict = status === "pass" ? "Passed" : status === "none" ? "Not found" : status === "fail" ? "Failed" : humanize(status);
  return { title: text[0], description: text[1], verdict };
}

function formatDuration(hops) {
  const times = hops.map(h => h.time?.getTime()).filter(Boolean);
  if (times.length < 2) return "—";
  const seconds = Math.max(...times) / 1000 - Math.min(...times) / 1000;
  if (seconds < 60) return `${Math.round(seconds)} sec`;
  if (seconds < 3600) return `${Math.floor(seconds / 60)}m ${Math.round(seconds % 60)}s`;
  return `${Math.floor(seconds / 3600)}h ${Math.round((seconds % 3600) / 60)}m`;
}

